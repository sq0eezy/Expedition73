"""Sample the two NOAA ETOPO 2022 source tiles at five-arc-minute intervals."""

import argparse
import hashlib
import json
import math
from pathlib import Path

from PIL import Image


BASE = "https://www.ngdc.noaa.gov/mgg/global/relief/ETOPO2022/data/15s/15s_surface_elev_gtif/"
TILES = {
    "A": ("ETOPO_2022_v1_15s_N45W120_surface.tif", [-113, 36, -109, 39]),
    "B": ("ETOPO_2022_v1_15s_N75W165_surface.tif", [-156, 68, -150, 70]),
}


def sample(path, bounds):
    west, south, east, north = bounds
    columns, rows = (east - west) * 12 + 1, (north - south) * 12 + 1
    with Image.open(path) as image:
        dx, dy, _ = image.tag_v2[33550]
        pixel_x, pixel_y, _, origin_lon, origin_lat, _ = image.tag_v2[33922]
        if image.mode != "F" or image.size != (3600, 3600) or dx != 1 / 240 or dy != 1 / 240:
            raise ValueError(f"Unexpected elevation grid in {path.name}")
        grid = []
        for row in range(rows):
            y = math.floor(pixel_y + (origin_lat - (north - row / 12)) / dy)
            line = []
            for column in range(columns):
                pixel = pixel_x + ((west + column / 12) - origin_lon) / dx
                # A window ending at the tile seam uses the nearest pixel
                # inside its own tile for the boundary vertex.
                x = image.width - 1 if column == columns - 1 and math.isclose(pixel, image.width) else math.floor(pixel)
                if not 0 <= x < image.width or not 0 <= y < image.height:
                    raise ValueError(f"Study window falls outside {path.name}")
                elevation = image.getpixel((x, y))
                if not math.isfinite(elevation) or elevation == float(image.tag_v2[42113]):
                    raise ValueError(f"Missing elevation in {path.name}")
                line.append(round(elevation))
            grid.append(line)
    return {"bounds": bounds, "source": BASE + path.name,
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "elevation": grid}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tiles", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    data = {region: sample(args.tiles / name, bounds) for region, (name, bounds) in TILES.items()}
    content = "// Generated by scripts/sample_terrain.py from NOAA ETOPO 2022.\n"
    content += "export const relief = " + json.dumps(data, separators=(",", ":")) + ";\n"
    args.output.write_text(content, encoding="utf-8", newline="\n")
